import type { Tier } from './progress';

/**
 * 상점 = 원하는 아바타를 골라 사는 곳.
 *
 * 소환은 무엇이 나올지 모르는 대신 싸고(1회 800), 상점은 확실한 대신 비싸다.
 * 둘 중 하나가 늘 이기면 다른 하나가 죽으니, 값은 '소환으로 그 아바타를
 * 뽑기까지 드는 기댓값'보다 조금 위에 둔다.
 *
 * 기댓값 계산 (등급 확률 / 그 등급의 종수 = 특정 한 종이 나올 확률):
 *   일반 55%/4종 = 13.75%  -> 약 7.3회  -> 5,800골드
 *   희귀 27%/4종 =  6.75%  -> 약 14.8회 -> 11,850
 *   영웅 13%/3종 =  4.33%  -> 약 23회   -> 18,500
 *   전설 4.3%/2종 = 2.15%  -> 약 46.5회 -> 37,200
 *   신화 0.7%/1종 = 0.7%   -> 약 143회  -> 114,300
 *
 * 숫자는 이 표에서만 만진다.
 */
export const AVATAR_PRICE: Record<Tier, number> = {
  common: 6000,
  rare: 13000,
  epic: 22000,
  legend: 45000,
  mythic: 130000,
};

export function avatarPrice(tier: Tier): number {
  return AVATAR_PRICE[tier];
}

