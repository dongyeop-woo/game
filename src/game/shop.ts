/**
 * 골드 충전 상품.
 *
 * 값은 아바타 가격표(`AVATAR_PRICE`)에 맞춰 잡는다 - 제일 싼 묶음으로
 * 일반 아바타 하나(6,000), 제일 비싼 묶음으로 신화(130,000)에 닿는다.
 * 많이 살수록 보너스가 붙어 한 골드당 값이 싸진다.
 *
 * **결제는 아직 연결돼 있지 않다.** 스토어(IAP) 붙이기 전까지 화면은
 * 상품만 보여 주고 실제로 사지지 않는다 - 돈이 빠져나가는 것처럼 보이는
 * 화면을 만들어 두면 안 된다.
 */
export interface GoldPack {
  id: string;
  /** 받는 골드 */
  gold: number;
  /** 덤으로 더 주는 골드 (0 이면 안 적는다) */
  bonus: number;
  /** 원화 */
  won: number;
}

